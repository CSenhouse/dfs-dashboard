"""Measure how two players in the same game actually co-move.

The optimizer treats every player as independent. They are not, and the
dependence is not a nuisance term -- it is most of what separates a cash
lineup from a tournament lineup. A QB and his WR1 rise and fall together, so
stacking them widens the distribution; a DST and the offence it is facing move
in opposite directions, so pairing them narrows it. Neither effect exists in a
sum of point projections.

What gets measured here is the dependence LEFT OVER after the model has had
its say. Raw score correlation is the wrong quantity: two players on a team
with a 30-point implied total both project high, and that shared signal is
already in both projections. Double-counting it would inflate every
correlation in the table.

So each observed score is first mapped through its own predicted distribution
(`simulate.pit`), which under a correct model is uniform, then to a normal
score. The correlation of those normal scores IS the Gaussian copula
parameter the simulator needs -- no rescaling step, no distributional
assumption about DK points themselves.

Input is walk-forward, never in-sample: an in-sample residual is too small and
too independent, and the table would come out near zero.

    PYTHONPATH=src .venv/Scripts/python.exe scripts/correlations.py

Writes src/dfs/correlations.py.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

from dfs import model, simulate
from dfs.config import CURATED

OUT = Path(__file__).resolve().parents[1] / "src" / "dfs" / "correlations.py"

# A pair is only kept if both players had a real chance of suiting up. Deep
# bench rows are mostly zeros against zeros, and their correlation is an
# artefact of the shared point mass rather than anything about football. They
# are also never rostered, so estimating on them would be measuring the wrong
# population to answer a question about lineups.
MIN_PLAY = 0.5

# Minimum pair count for a cell to be trusted at all, and the shrinkage
# constant: an estimate from n games is pulled toward zero by n / (n + PRIOR).
# Rare cells (a kicker against an opposing TE2) would otherwise enter the
# covariance matrix at full strength on a handful of observations.
MIN_PAIRS = 200
PRIOR = 400.0


def normal_scores(df: pd.DataFrame, seed: int = 0) -> np.ndarray:
    grid = df[model.quantile_columns(df)].to_numpy(dtype=float, copy=True)
    grid.sort(axis=1)
    u = simulate.pit(df["dk_scored"].to_numpy(dtype=float), grid,
                     df["p_play"].to_numpy(dtype=float), seed=seed)
    return stats.norm.ppf(u)


def pairs(df: pd.DataFrame, min_play: float) -> pd.DataFrame:
    """Every within-game pair, labelled by relationship and depth role."""
    df = df.copy()
    df["z"] = normal_scores(df)
    df["role"] = ""
    for _, g in df.groupby(["season", "week"], sort=False):
        df.loc[g.index, "role"] = simulate.roles(g)
    df["game"] = simulate._game_key(df)

    rows = []
    for _, g in df.groupby(["season", "week", "game"], sort=False):
        if len(g) < 2:
            continue
        g = g[g["p_play"] >= min_play]
        if len(g) < 2:
            continue
        i, j = np.triu_indices(len(g), k=1)
        team = g["team"].astype(str).to_numpy()
        role = g["role"].to_numpy()
        z = g["z"].to_numpy()
        a = np.minimum(role[i], role[j])
        b = np.maximum(role[i], role[j])
        rows.append(pd.DataFrame({
            "rel": np.where(team[i] == team[j], "team", "opp"),
            "a": a, "b": b, "zi": z[i], "zj": z[j],
        }))
    return pd.concat(rows, ignore_index=True) if rows else pd.DataFrame()


def table(pr: pd.DataFrame) -> pd.DataFrame:
    out = []
    for (rel, a, b), g in pr.groupby(["rel", "a", "b"], sort=False):
        if len(g) < 2:
            continue
        r = float(np.corrcoef(g["zi"], g["zj"])[0, 1])
        if not np.isfinite(r):
            continue
        out.append({"rel": rel, "a": a, "b": b, "n": len(g), "raw": r,
                    "r": round(r * len(g) / (len(g) + PRIOR), 4)})
    got = pd.DataFrame(out)
    if got.empty:
        return got
    return got[got["n"] >= MIN_PAIRS].sort_values("r").reset_index(drop=True)


def write_module(t: pd.DataFrame, source: str, min_play: float) -> None:
    lines = [
        '"""Copula correlations between two players in the same NFL game.',
        "",
        "GENERATED by scripts/correlations.py -- edit that, not this.",
        "",
        f"Estimated on {source}: walk-forward normal scores, so the numbers are",
        "what is left after each player's own projected distribution is divided",
        "out, not raw score correlation. Pairs are kept only where both players",
        f"had P(plays) >= {min_play}, and each cell is shrunk toward zero by",
        f"n / (n + {PRIOR:.0f}) so a thin cell cannot dominate a covariance matrix.",
        "",
        "Keys are (relationship, role, role) with the roles sorted. Roles carry",
        "depth within the team (WR1/WR2/WR3), because a quarterback's",
        "relationship with his top receiver is not his relationship with his",
        "third. Absent pairs are treated as independent.",
        '"""',
        "CORRELATION: dict[tuple[str, str, str], float] = {",
    ]
    for r in t.sort_values(["rel", "a", "b"]).itertuples():
        lines.append(
            f'    ("{r.rel}", "{r.a}", "{r.b}"): {r.r:+.4f},'
            f'  # n={r.n:,}, raw {r.raw:+.3f}'
        )
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main(argv: list[str]) -> int:
    showdown = "--showdown" in argv
    src = ("showdown_sim_predictions.parquet" if showdown
           else "sim_predictions.parquet")
    path = CURATED / src
    if not path.exists():
        print(f"{path} missing -- run scripts/build_simulation_inputs.py first",
              file=sys.stderr)
        return 1

    df = pd.read_parquet(path)
    print(f"{len(df):,} player-weeks", flush=True)

    pr = pairs(df, MIN_PLAY)
    print(f"{len(pr):,} within-game pairs at P(play) >= {MIN_PLAY}\n", flush=True)
    t = table(pr)
    if t.empty:
        print("no cell met the minimum pair count", file=sys.stderr)
        return 1

    print("=== strongest relationships (shrunk) ===")
    show = pd.concat([t.head(10), t.tail(12)])
    for r in show.itertuples():
        print(f"  {r.rel:<4} {r.a:<5} {r.b:<5} r={r.r:+.3f}  "
              f"(raw {r.raw:+.3f}, n={r.n:,})")

    write_module(t, src, MIN_PLAY)
    print(f"\n{len(t)} cells -> {OUT.relative_to(OUT.parents[3])}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
