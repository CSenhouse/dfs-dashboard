"""The model is confident in exactly the wrong place, and not symmetrically.

Pooled over every priced player the predicted distributions look near perfect:
PIT deciles 0.092 to 0.106, KS 0.016. Split by projection and that average is
two opposite errors cancelling.

    decile 0 (punts)     82-83% inside its own 80% interval -- too WIDE
    decile 9 (the studs) 74.3%                              -- too NARROW

The top decile is the only bucket the optimizer ever rosters from, so the
error that survives into a lineup is the one the pooled number hides, and it
runs the dangerous way: nine players each drawn a little too tightly make a
lineup that looks far safer than it is.

The narrowness is LOPSIDED. For the top decile, against what actually
happened:

    q30 predicted 11.21   actual 10.32   too high by 0.89
    q50 predicted 15.08   actual 14.86   about right
    q85 predicted 23.44   actual 25.53   too low by 2.09

The upper end is wrong by more than twice as much as the lower, so a single
multiplier around the median cannot fix both. It also leaves the distribution
with the wrong MEAN: sampling the grid for a top-decile player returns 15.79
against the 16.73 the model's own mean regressor predicts for him, and across
nine players that is 8.4 points a lineup. The simulator was quietly disagreeing
with the projection it sits next to.

So two numbers per bucket, one for each side of the median, each fitted in
closed form. Under a widening s, an observed result at normal score z moves to
z / s, so the factor that puts exactly 10% of results past the 10th percentile
is just that percentile divided by the standard normal's own. No search.

Fitted on early seasons and checked on later ones, never on the same rows.
Fitted in-sample it would always report a perfect fix.

    PYTHONPATH=src .venv/Scripts/python.exe scripts/calibrate_spread.py

Writes src/dfs/spread.py.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

from dfs import model, simulate
from dfs.config import CURATED

OUT = Path(__file__).resolve().parents[1] / "src" / "dfs" / "spread.py"

BUCKETS = 10
TRAIN_SEASONS = (2021, 2022, 2023)

# The defect is real but its SIZE is not stable across seasons, so a
# correction fitted at full strength on the first three overshoots the last
# two. Applied as s ** SHRINK. The sweep below reports what each strength buys
# on seasons the fit has never seen.
SHRINK = 0.5
LO, HI = 0.10, 0.90
Z = stats.norm.ppf(HI)


def pit_of(df: pd.DataFrame, seed: int = 3) -> np.ndarray:
    grid = df[model.quantile_columns(df)].to_numpy(dtype=float, copy=True)
    grid.sort(axis=1)
    return simulate.pit(df["dk_scored"].to_numpy(float), grid,
                        df["p_play"].to_numpy(float), seed=seed)


def bucketed(df: pd.DataFrame) -> pd.Series:
    """Projection decile WITHIN the slate, so it means the same every week."""
    return df.groupby(["season", "week"])["projection"].transform(
        lambda s: pd.qcut(s.rank(method="first"), BUCKETS, labels=False)
    )


def widen(u: np.ndarray, lo: float, hi: float) -> np.ndarray:
    """Re-express an observed PIT under a distribution widened by (lo, hi).

    The two factors act on opposite sides of the median, so the correction can
    stretch a distribution's upper end further than its lower -- which is what
    the measurements ask for, and what a single factor cannot do.
    """
    z = stats.norm.ppf(np.clip(u, 1e-9, 1 - 1e-9))
    return stats.norm.cdf(z / np.where(z < 0, lo, hi))


def fit_bucket(u: np.ndarray) -> tuple[float, float]:
    """Closed form: the widening that puts exactly 10% in each tail."""
    if u.size < 200:
        return 1.0, 1.0
    z = stats.norm.ppf(np.clip(u, 1e-9, 1 - 1e-9))
    return float(-np.percentile(z, 100 * LO) / Z), float(np.percentile(z, 100 * HI) / Z)


def report(df: pd.DataFrame, table: dict, label: str) -> None:
    print(f"\n=== {label} ===")
    print("  bucket        n    below .10  above .90   inside   after: lo/hi/in")
    for b, g in df.groupby("bucket"):
        u = g["u"].to_numpy()
        lo, hi = table.get(int(b), (1.0, 1.0))
        v = widen(u, lo, hi)
        a, c = (u < LO).mean(), (u > HI).mean()
        d, e = (v < LO).mean(), (v > HI).mean()
        print(f"    {int(b):<4} {len(g):>7,}    {a:6.1%}     {c:6.1%}   {1-a-c:6.1%}"
              f"    {d:.1%}/{e:.1%}/{1-d-e:.1%}")


def write_module(table: dict, train: tuple, test: list) -> None:
    lines = [
        '"""How much to widen a predicted distribution, by projection decile.',
        "",
        "GENERATED by scripts/calibrate_spread.py -- edit that, not this.",
        "",
        "The model is well calibrated on average and overconfident where it",
        "matters. Pooled across every priced player the PIT is nearly uniform,",
        "but the top projection decile -- the only bucket an optimizer rosters",
        "from -- covers about 74% of results inside its own 80% interval while",
        "the punt end covers 83%. The average of a too-wide and a too-narrow",
        "error looks perfect and is not.",
        "",
        "Two factors per bucket because the narrowness is lopsided: for the top",
        "decile q30 is too high by 0.89 and q85 too low by 2.09, so the upper",
        "end needs stretching about twice as hard as the lower. A single",
        "factor around the median also left the grid's implied mean 0.93 below",
        "the model's own mean regressor for the same player -- 8.4 points",
        "across a lineup.",
        "",
        "Each value multiplies the normal score before it is mapped through the",
        "player's quantile function: SPREAD_LO below the median, SPREAD_HI",
        "above. Bucket 0 is the lowest projection on the slate, 9 the highest.",
        "",
        f"Fitted on seasons {', '.join(str(s) for s in train)} and checked on",
        f"{', '.join(str(s) for s in test)}, then applied at SHRINK={SHRINK}:",
        "the defect is real but its size is not stable season to season, and a",
        "full-strength correction overshoots the held-out years.",
        '"""',
        f"BUCKETS = {BUCKETS}",
        "SPREAD_LO: dict[int, float] = {",
    ]
    for b in sorted(table):
        lines.append(f"    {b}: {table[b][0]:.4f},")
    lines.append("}")
    lines.append("SPREAD_HI: dict[int, float] = {")
    for b in sorted(table):
        lines.append(f"    {b}: {table[b][1]:.4f},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main(argv: list[str]) -> int:
    path = CURATED / "sim_predictions.parquet"
    if not path.exists():
        print(f"{path} missing -- run scripts/build_simulation_inputs.py",
              file=sys.stderr)
        return 1

    df = pd.read_parquet(path).reset_index(drop=True)
    df["u"] = pit_of(df)
    df["bucket"] = bucketed(df)
    df = df.dropna(subset=["bucket", "u"])
    df["bucket"] = df["bucket"].astype(int)

    train = df[df["season"].isin(TRAIN_SEASONS)]
    test = df[~df["season"].isin(TRAIN_SEASONS)]
    held = sorted(test["season"].unique())
    print(f"fit on {len(train):,} rows from {TRAIN_SEASONS}, "
          f"check on {len(test):,} rows from {tuple(held)}")

    raw = {int(b): fit_bucket(g["u"].to_numpy())
           for b, g in train.groupby("bucket")}
    table = {b: (lo ** SHRINK, hi ** SHRINK) for b, (lo, hi) in raw.items()}
    print("\nfitted widening, full strength (lower / upper):")
    print("  " + "  ".join(f"{b}:{raw[b][0]:.2f}/{raw[b][1]:.2f}"
                           for b in sorted(raw)))
    print(f"applied at SHRINK={SHRINK}:")
    print("  " + "  ".join(f"{b}:{table[b][0]:.2f}/{table[b][1]:.2f}"
                           for b in sorted(table)))

    print("\n=== held-out sweep: what each strength buys ===")
    print("  lambda   all players   pooled KS   top decile (what gets rostered)")
    for lam in (0.0, 0.25, 0.5, 0.75, 1.0):
        vs, top = [], float("nan")
        for b, g in test.groupby("bucket"):
            lo, hi = raw.get(int(b), (1.0, 1.0))
            v = widen(g["u"].to_numpy(), lo ** lam, hi ** lam)
            vs.append(v)
            if int(b) == BUCKETS - 1:
                top = float(((v >= LO) & (v <= HI)).mean())
        v = np.concatenate(vs)
        print(f"    {lam:.2f}       {((v >= LO) & (v <= HI)).mean():.1%}        "
              f"{stats.kstest(v, 'uniform').statistic:.4f}      {top:.1%}")

    report(train, table, "training seasons (in-sample -- expect a good fit)")
    report(test, table, "held-out seasons (the number that counts)")

    write_module(table, TRAIN_SEASONS, held)
    print(f"\n-> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
